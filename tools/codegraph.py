"""Compact code graph for cheap navigation (stdlib only).

python tools/codegraph.py build          # write CODEGRAPH.md
python tools/codegraph.py check          # fail if stale or layer rule broken
python tools/codegraph.py find NAME      # where is a symbol defined
python tools/codegraph.py deps MOD       # internal modules MOD imports
python tools/codegraph.py rdeps MOD      # modules (incl. tests) importing MOD, transitively
python tools/codegraph.py tests PATH...  # test files affected by these source paths
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
OUT = ROOT / "CODEGRAPH.md"
PKG = "pi_tool"

# Layer -> layers it may import. core stays pure; platform is the only Windows-touching layer.
LAYERS = {
    "pi_tool.core": {"pi_tool.core"},
    "pi_tool.vision": {"pi_tool.core", "pi_tool.vision"},
    "pi_tool.platform": {"pi_tool.core", "pi_tool.platform"},
    "pi_tool.app": {"pi_tool.core", "pi_tool.vision", "pi_tool.platform", "pi_tool.app"},
}
# Third-party imports forbidden per layer (keeps core testable on Linux CI).
FORBIDDEN_EXT = {
    "pi_tool.core": {"cv2", "numpy", "PySide6", "win32api", "win32gui", "mss", "ctypes"},
    "pi_tool.vision": {"PySide6", "win32api", "win32gui", "mss", "ctypes"},
}


def mod_name(path: Path) -> str:
    rel = path.relative_to(SRC if path.is_relative_to(SRC) else ROOT).with_suffix("")
    parts = list(rel.parts)
    if parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def files() -> list[Path]:
    out = sorted((SRC / PKG).rglob("*.py"))
    return out + sorted((ROOT / "tests").rglob("test_*.py"))


def first_line(node) -> str:
    doc = ast.get_docstring(node)
    return doc.strip().splitlines()[0] if doc else ""


def sig(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    a = ast.unparse(fn.args)
    ret = f" -> {ast.unparse(fn.returns)}" if fn.returns else ""
    return f"{fn.name}({a}){ret}"


def parse(path: Path):
    tree = ast.parse(path.read_text(encoding="utf-8"))
    imports, ext = set(), set()
    for n in ast.walk(tree):
        if isinstance(n, ast.Import):
            names = [a.name for a in n.names]
        elif isinstance(n, ast.ImportFrom) and n.module and n.level == 0:
            names = [n.module]
        else:
            continue
        for name in names:
            if name.startswith(PKG):
                imports.add(name)
            elif name.split(".")[0] not in sys.stdlib_module_names:
                ext.add(name)  # third-party only: stdlib is noise
    syms = []
    for n in tree.body:
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and not n.name.startswith("_"):
            syms.append((n.lineno, f"def {sig(n)}", first_line(n), []))
        elif isinstance(n, ast.ClassDef) and not n.name.startswith("_"):
            bases = ", ".join(ast.unparse(b) for b in n.bases)
            members = [
                f".{sig(m)}"
                for m in n.body
                if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef))
                and (not m.name.startswith("_"))
            ]
            head = f"class {n.name}({bases})" if bases else f"class {n.name}"
            syms.append((n.lineno, head, first_line(n), members))
        elif isinstance(n, (ast.Assign, ast.AnnAssign)):
            targets = n.targets if isinstance(n, ast.Assign) else [n.target]
            for t in targets:
                if isinstance(t, ast.Name) and t.id.isupper():
                    syms.append((n.lineno, f"{t.id} = {ast.unparse(n.value)[:60]}", "", []))
    return {"doc": first_line(tree), "imports": imports, "ext": ext, "syms": syms}


def graph() -> dict[str, dict]:
    g = {}
    for p in files():
        info = parse(p)
        info["path"] = p.relative_to(ROOT).as_posix()
        g[mod_name(p)] = info
    return g


def resolve(g: dict, name: str) -> str | None:
    """Map an import like pi_tool.core.grid.Calibration to a known module."""
    while name and name not in g:
        name = name.rpartition(".")[0]
    return name or None


def render(g: dict) -> str:
    lines = [
        "# CODEGRAPH (generated by tools/codegraph.py — do not edit)",
        "Read this instead of opening files. `path:line` for each symbol.",
        "",
    ]
    for m, info in g.items():
        if m.startswith("tests"):
            continue
        deps = sorted({resolve(g, i) or i for i in info["imports"]} - {m})
        lines.append(f"## {m} — {info['path']}" + (f" — {info['doc']}" if info["doc"] else ""))
        if deps:
            lines.append(f"uses: {', '.join(deps)}")
        if info["ext"]:
            lines.append(f"ext: {', '.join(sorted(info['ext']))}")
        for ln, head, doc, members in info["syms"]:
            lines.append(f"- :{ln} {head}" + (f" — {doc}" if doc else ""))
            lines.extend(f"  - {mm}" for mm in members)
    tests = [
        f"{info['path']} → {', '.join(sorted({resolve(g, i) or i for i in info['imports']}))}"
        for m, info in g.items()
        if m.startswith("tests")
    ]
    lines += ["", "## tests", *(f"- {t}" for t in tests)]
    return "\n".join(lines) + "\n"


def layer_of(m: str) -> str | None:
    return next((lay for lay in LAYERS if m == lay or m.startswith(lay + ".")), None)


def violations(g: dict) -> list[str]:
    out = []
    for m, info in g.items():
        lay = layer_of(m)
        if not lay:
            continue
        for i in info["imports"]:
            tgt = layer_of(resolve(g, i) or i)
            if tgt and tgt not in LAYERS[lay]:
                out.append(f"{info['path']}: {lay} must not import {i}")
        for e in info["ext"]:
            if e.split(".")[0] in FORBIDDEN_EXT.get(lay, ()):
                out.append(f"{info['path']}: {lay} must not import {e}")
    return out


def rdeps(g: dict, target: str) -> set[str]:
    rev: dict[str, set[str]] = {}
    for m, info in g.items():
        for i in info["imports"]:
            r = resolve(g, i)
            if r:
                rev.setdefault(r, set()).add(m)
    seen, stack = set(), [target]
    while stack:
        for d in rev.get(stack.pop(), ()):
            if d not in seen:
                seen.add(d)
                stack.append(d)
    return seen


def main(argv: list[str]) -> int:
    cmd, args = (argv[0], argv[1:]) if argv else ("build", [])
    g = graph()
    if cmd == "build":
        OUT.write_text(render(g), encoding="utf-8")
        bad = violations(g)
        print(*bad, sep="\n", file=sys.stderr)
        return 1 if bad else 0
    if cmd == "check":
        errs = violations(g)
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != render(g):
            errs.append("CODEGRAPH.md stale: run ./dev graph")
        print(*errs, sep="\n")
        return 1 if errs else 0
    if cmd == "find":
        for info in g.values():
            for ln, head, _doc, members in info["syms"]:
                hit = args[0] in head or any(args[0] in mm for mm in members)
                if hit:
                    print(f"{info['path']}:{ln} {head}")
        return 0
    if cmd == "deps":
        print(*sorted({resolve(g, i) or i for i in g[args[0]]["imports"]}), sep="\n")
        return 0
    if cmd == "rdeps":
        print(*sorted(rdeps(g, args[0])), sep="\n")
        return 0
    if cmd == "tests":
        hit = set()
        for a in args:
            p = (ROOT / a).resolve()
            if p.name.startswith("test_"):
                hit.add(p.relative_to(ROOT).as_posix())
            elif p.suffix == ".py" and p.is_relative_to(SRC):
                m = mod_name(p)
                hit |= {g[d]["path"] for d in rdeps(g, m) | {m} if d.startswith("tests")}
        print(*sorted(hit), sep="\n")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
